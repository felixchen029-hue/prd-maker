import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
const require=createRequire(import.meta.url),R=require('../assets/report-charts.cjs');
const input=JSON.parse(fs.readFileSync(new URL('../assets/example.request.json',import.meta.url),'utf8'));
const a=R.render(input),b=R.render(input);
const digest=svg=>createHash('sha256').update(svg).digest('hex');
assert.equal(digest(a.svg),digest(b.svg),'Same request must produce byte-identical SVG');
assert.equal(a.total.revenue,40200000);
assert.equal(a.total.profit,24230000);
assert.equal(a.total.cost,15150000);
assert.equal(a.total.gap,820000);
assert.ok(a.svg.includes('linearGradient'));
assert.ok(!a.svg.includes('foreignObject'));
assert.ok(!/<image\b/.test(a.svg));
const texture=R.render({...input,style:{fill:'gradient-texture'}});
assert.ok(texture.svg.includes('<pattern'));
const ranked=R.render({...input,chart:'revenue',style:{orientation:'horizontal',showTable:false}});
assert.ok(!ranked.svg.includes('data-role="summary-table"'));
const aligned=R.render({...input,style:{stackBasis:'aligned'}});
for(const g of aligned.groups)assert.ok(Math.abs((g.revenue-g.profit)+g.profit-g.revenue)<.01);
assert.ok(aligned.warnings.some(v=>v.includes('推导成本')));
const neg={...input,data:[{industry:'负值测试',revenue:-100,cost:20,profit:-125}]};
assert.ok(R.render(neg).warnings.some(v=>v.includes('含负值')));
assert.ok(R.render({...neg,chart:'share'}).warnings.some(v=>v.includes('负收入')));
const zero=R.render({...input,data:[{industry:'零收入',revenue:0,cost:0,profit:0}]});
assert.equal(zero.total.margin,null);
assert.throws(()=>R.render({...input,style:{fill:'arbitrary-css'}}));
assert.throws(()=>R.render({...input,style:{fontSize:NaN}}));
assert.throws(()=>R.render({...input,style:{myCSS:'anything'}}));
assert.throws(()=>R.render({...input,data:[{industry:'空值',revenue:'',cost:0,profit:0}]}));
const project=R.normalize(input),before=R.render(project);
project.settings.tableGap+=20;
const after=R.render(project);
assert.equal(after.total.revenue,before.total.revenue);
assert.notEqual(after.svg,before.svg);
const updated=R.normalize(input);updated.rows[0].revenue+=10000;
assert.equal(R.render(updated).total.revenue,a.total.revenue+10000);
assert.equal(updated.settings.fill,a.project.settings.fill);
const crowded=R.render({...input,chart:'compare',data:Array.from({length:24},(_,i)=>({industry:'较长行业名称'+i,revenue:10000000+i,cost:2000000,profit:7800000})),style:{showTable:true,top:0,orientation:'vertical'}});
assert.ok(crowded.warnings.some(v=>v.includes('类别较密')));
assert.ok(crowded.option.series.every(series=>!series.label.show));
const missingMargin=R.render({...input,chart:'margin',data:[{industry:'零收入',revenue:0,cost:0,profit:0}]});
assert.equal(missingMargin.option.series[0].data[0].value,null);
console.log(JSON.stringify({status:'passed',svgSHA256:digest(a.svg),engine:R.VERSION}));
